/// Defines the visual style variant of a [NasikoChip].
enum NasikoChipVariant {
  /// Neutral chip with gray background - for unselected/default state.
  neutral,

  /// Brand colored chip with yellow background - for selected state.
  brand,

  /// Base chip with backgroundBase color - for use with rounded shape.
  base,

  /// Base chip with yellow50 color - for use as tags.

  tag,
}
