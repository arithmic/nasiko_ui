/// Enum representing the available color palettes in Nasiko UI.
///
/// Each palette type corresponds to a distinct color scheme that can be
/// used to dynamically theme your application.
enum NasikoColorPalette {
  /// Yellow-based palette (default)
  yellow,

  /// Orange-based palette
  orange,

  /// Red-based palette
  red,

  /// Purple-based palette
  purple,

  /// Blue-based palette
  blue,

  /// Teal-based palette
  teal,

  /// Green-based palette
  green,
}
